test "every translated template uses only arguments the English one has" {
    @setEvalBranchQuota(100_000);
    // A translation can drop arguments but must not name one callers never pass.
    inline for (all) |entry| {
        inline for (@typeInfo(Messages).@"struct".field_names) |name| {
            const english = @field(Messages.english, name);
            const translated = @field(entry[1].*, name);
            for (0..4) |n| {
                var tag: [3]u8 = .{ '{', '0' + @as(u8, @intCast(n)), '}' };
                const used = std.mem.indexOf(u8, translated, &tag) != null;
                const allowed = std.mem.indexOf(u8, english, &tag) != null;
                if (used and !allowed) {
                    std.debug.print("{s}.{s} uses {s}\n", .{ entry[0], name, &tag });
                    return error.TestUnexpectedResult;
                }
            }
        }
    }
}

test "every table translates every sentence" {
    @setEvalBranchQuota(100_000);
    inline for (all) |entry| {
        inline for (@typeInfo(Messages).@"struct".field_names) |name| {
            // Sentences that are only marks and arguments stay as they are.
            const skip = comptime std.mem.eql(u8, name, "response_file") or
                std.mem.eql(u8, name, "flow_failed");
            const english = @field(Messages.english, name);
            if (!skip and std.mem.eql(u8, english, @field(entry[1].*, name))) {
                std.debug.print("{s}.{s} is English\n", .{ entry[0], name });
                return error.TestUnexpectedResult;
            }
        }
    }
}
