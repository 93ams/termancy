/// Every table here, by language, for `i18n.Translation.messages`.
pub const all = [_]struct { []const u8, *const Messages }{
    .{ "de", &german },
    .{ "es", &spanish },
    .{ "fr", &french },
    .{ "pt", &portuguese },
